def build_specialization_benchmark_schedule(
    fragments: list[dict[str, Any]],
    total_rounds: int = 8,
) -> list[dict[str, Any]]:
    """
    Build a balanced Use-Case Specialization schedule:
      - 2 APPEND rounds (delicate live mutation & layer addition)
      - 2 COMPOSE rounds (structural algorithmic composition & timeline score)
      - 2 DESIGN rounds (playable hardware MIDI + multi-zone GUI synth design)
      - 2 GENERATE rounds (autonomous multi-layered evolving soundscape)
    """
    frag_by_id = {f["id"]: f for f in fragments}

    # Curated targets from the 200-fragment corpus:
    spec_items = [
        ("append", 149),     # Verissimo - delicate domestic conversation
        ("append", 120),     # Castro Alves - dramatic stormy ocean layer
        ("compose", 50),     # Relojoeiro de Ouro Preto - polyrhythmic clockwork score
        ("compose", 13),     # Gruta do Maquiné - reverberant subterranean acoustic space
        ("design", 74),      # Buchla modular & oscilloscope - interactive hardware design
        ("design", 86),      # Berimbau de barriga - expressive physical model
        ("generate", 92),    # Congada - multi-layer polyphonic percussive ceremony
        ("generate", 173),   # Entardecer no Pantanal - evolving ecological soundscape
    ]

    if total_rounds != len(spec_items):
        if total_rounds < len(spec_items):
            spec_items = spec_items[:total_rounds]
        else:
            # Repeat to reach total_rounds
            extra = [("append", 155), ("compose", 55)]
            spec_items = (spec_items + extra)[:total_rounds]

    schedule = []
    mode_counts: dict[str, int] = {}
    for idx, (m, fid) in enumerate(spec_items, start=1):
        frag = frag_by_id.get(fid)
        if not frag:
            frag = fragments[fid % len(fragments)]
        mode_counts[m] = mode_counts.get(m, 0) + 1
        schedule.append({
            "round_index": idx,
            "mode": m,
            "mode_occurrence": mode_counts[m],
            "requires_design_cleanup": (m == "design" and mode_counts["design"] > 1),
            "fragment_id": frag["id"],
            "fragment_category": frag["category"],
            "fragment_source": frag["source"],
            "prompt": frag["text"],
        })
    return schedule


def build_10_round_benchmark_schedule(
    fragments: list[dict[str, Any]],
    total_rounds: int = 10,
    seed: int = 101,
) -> list[dict[str, Any]]:
    """
    Build a balanced 10-round X-Append schedule:
      - append: 3 rounds
      - compose: 3 rounds
      - design: 2 rounds
      - generate: 2 rounds
      = 10 rounds total.
    Samples 10 distinct fragments from the corpus using fixed seed so all
    models are tested against the EXACT same prompt sequence.
    """
    rng = random.Random(seed)
    chosen_frags = rng.sample(fragments, total_rounds)

    base_modes = ["append", "compose", "design", "generate", "append", "compose", "design", "generate", "compose", "append"]
    if total_rounds <= len(base_modes):
        modes = base_modes[:total_rounds]
    else:
        modes = (base_modes * ((total_rounds // len(base_modes)) + 1))[:total_rounds]
    assert len(modes) == total_rounds

    schedule = []
    mode_counts: dict[str, int] = {}
    for idx, (m, frag) in enumerate(zip(modes, chosen_frags), start=1):
        mode_counts[m] = mode_counts.get(m, 0) + 1
        schedule.append({
            "round_index": idx,
            "mode": m,
            "mode_occurrence": mode_counts[m],
            "requires_design_cleanup": (m == "design" and mode_counts["design"] > 1),
            "fragment_id": frag["id"],
            "fragment_category": frag["category"],
            "fragment_source": frag["source"],
            "prompt": frag["text"],
        })
    return schedule


def run_benchmark_for_model(
    model_info: dict[str, str],
    schedule: list[dict[str, Any]],
    validator: SclangParallelValidator,
    max_fix_attempts: int = DEFAULT_MAX_FIX_ATTEMPTS,
    outdir: str = "",
    verbose: bool = True,
    use_kb: bool = False,
    session_suffix: str = "",
) -> dict[str, Any]:
    """Execute the benchmark schedule for a single model."""
    model_id = model_info["id"]
    model_name = model_info["name"]
    model_slug = model_info["slug"]

    if verbose:
        kb_tag = "WITH KB" if use_kb else "NO KB"
        print(f"\n{'='*78}\nBENCHMARKING MODEL: {model_name} ({model_id}) [{kb_tag}]\n{'='*78}", flush=True)

    session_scd = os.path.join(outdir, f"session_{model_slug}{session_suffix}.scd")
    with open(session_scd, "w", encoding="utf-8") as f:
        f.write(
            f"// ============================================================\n"
            f"// MULTI-PROVIDER BENCHMARK: {model_name}\n"
            f"// Model ID: {model_id}\n"
            f"// Date: {datetime.now(timezone.utc).isoformat()}\n"
            f"// ============================================================\n\n"
        )

    # Reset GUI backend state
    gui_backend._composition_states[session_scd] = ""
    gui_backend._design_ran_in_session[session_scd] = False

    rounds_data: list[dict[str, Any]] = []
    generated_codes: list[dict[str, Any]] = []
    design_runs_completed = 0

    t_model_start = time.perf_counter()

    for item in schedule:
        r_idx = item["round_index"]
        mode = item["mode"]
        mode_occ = item["mode_occurrence"]
        prompt = item["prompt"]
        frag_id = item["fragment_id"]
        frag_cat = item["fragment_category"]
        frag_src = item["fragment_source"]

        r_t0 = time.perf_counter()
        needs_design_cleanup = (mode == "design" and design_runs_completed >= 1)
        design_cleanup_time_s = 0.0

        if verbose:
            print(
                f"\n--- [{model_name}] [Round {r_idx:02d}/{len(schedule):02d}] "
                f"MODE={mode.upper()} (#{mode_occ}) | Frag #{frag_id} ({frag_cat}) ---",
                flush=True,
            )

        if needs_design_cleanup and hasattr(validator, "run_design_cleanup"):
            _, design_cleanup_time_s = validator.run_design_cleanup()

        payload = {
            "mode": mode,
            "lean_prompt": True,
            "use_kb": use_kb,
            "prompt": prompt,
            "model": model_id,
            "active_file": session_scd,
            "cleanup_previous_design": needs_design_cleanup,
        }

        # 1. Generate code via lean prompt (2-minute API timeout guard)
        API_TIMEOUT_S = 120.0
        lean_t0 = time.perf_counter()
        api_timed_out = False
        api_error_msg = ""
        executor = concurrent.futures.ThreadPoolExecutor(max_workers=1)
        try:
            future = executor.submit(gui_backend.cmd_cross_append, payload)
            res = future.result(timeout=API_TIMEOUT_S)
        except concurrent.futures.TimeoutError:
            api_timed_out = True
            api_error_msg = f"API Timeout: cmd_cross_append exceeded {API_TIMEOUT_S:.0f}s"
            res = {"code": f"// {api_error_msg}", "last_stats": {"time_s": API_TIMEOUT_S}}
        except Exception as exc:
            api_timed_out = True
            api_error_msg = f"API Error: {exc}"
            res = {"code": f"// {api_error_msg}", "last_stats": {"time_s": time.perf_counter() - lean_t0}}
        finally:
            executor.shutdown(wait=False, cancel_futures=True)
        lean_wall_s = time.perf_counter() - lean_t0

        # Wait for state thread
        evt = gui_backend._composition_state_events.get(session_scd)
        if evt and not evt.is_set():
            evt.wait(timeout=10.0)

        code = res.get("code", "")
        stats = res.get("last_stats", {}) or {}
        rag_fallback = res.get("rag_fallback", "")
        validator_fixes = list(res.get("validator_fixes", []))
        design_cleanup_applied = bool(
            res.get("design_cleanup_applied", False)
            or (needs_design_cleanup and DESIGN_PRE_CLEANUP_MARKER in code)
        )

        if needs_design_cleanup and code and DESIGN_PRE_CLEANUP_MARKER not in code:
            code, prepended = prepend_design_cleanup(code)
            if prepended:
                design_cleanup_applied = True
                validator_fixes.append("prepended pre-design synthesizer cleanup")

        lean_llm_s = float(stats.get("time_s", 0.0) or lean_wall_s)
        in_tokens = int(stats.get("in_tokens", 0) or 0)
        out_tokens = int(stats.get("out_tokens", 0) or 0)
        cost_usd = float(stats.get("cost", 0.0) or 0.0)

        # 2. Validate on sclang (skip if API timed out)
        if api_timed_out:
            initial_valid, initial_error, initial_val_s = False, api_error_msg, 0.0
        else:
            initial_valid, initial_error, initial_val_s = validator.validate_code(code, mode=mode)

        if verbose:
            tag = "PASS" if initial_valid else "FAIL"
            print(
                f"  [LEAN {mode.upper()}] wall={lean_wall_s:.2f}s (llm={lean_llm_s:.2f}s) "
                f"| tokens={in_tokens}->{out_tokens} (${cost_usd:.5f}) "
                f"| val={tag} ({initial_val_s:.2f}s)",
                flush=True,
            )
            if not initial_valid:
                print(f"  [ERROR] {initial_error.splitlines()[0][:100]}", flush=True)

        # 3. Auto-fix loop if invalid
        auto_fix_triggered = not initial_valid
        auto_fix_attempts = 0
        auto_fix_succeeded = False
        resolved_attempt = 0 if initial_valid else -1
        current_code = code
        current_error = initial_error
        fix_records: list[dict[str, Any]] = []

        if auto_fix_triggered and not api_timed_out and max_fix_attempts > 0:
            for fix_i in range(1, max_fix_attempts + 1):
                auto_fix_attempts += 1
                fix_t0 = time.perf_counter()
                fix_payload = {
                    "block": current_code,
                    "error": current_error,
                    "mode": mode,
                    "is_cross_append": True,
                    "cleanup_previous_design": needs_design_cleanup,
                    "model": model_id,
                    "active_file": session_scd,
                }
                fix_timed_out = False
                fix_err_msg = ""
                fix_exec = concurrent.futures.ThreadPoolExecutor(max_workers=1)
                try:
                    fix_future = fix_exec.submit(gui_backend.cmd_fix, fix_payload)
                    fix_res = fix_future.result(timeout=API_TIMEOUT_S)
                except concurrent.futures.TimeoutError:
                    fix_timed_out = True
                    fix_err_msg = f"API Timeout: cmd_fix exceeded {API_TIMEOUT_S:.0f}s"
                    fix_res = {"code": current_code, "last_stats": {"time_s": API_TIMEOUT_S}}
                except Exception as exc:
                    fix_timed_out = True
                    fix_err_msg = f"API Error: {exc}"
                    fix_res = {"code": current_code, "last_stats": {"time_s": time.perf_counter() - fix_t0}}
                finally:
                    fix_exec.shutdown(wait=False, cancel_futures=True)
                fix_wall_s = time.perf_counter() - fix_t0
                fixed_code = fix_res.get("code", "")
                fix_stats = fix_res.get("last_stats", {}) or {}
                fix_llm_s = float(fix_stats.get("time_s", 0.0) or fix_wall_s)
                f_in = int(fix_stats.get("in_tokens", 0) or 0)
                f_out = int(fix_stats.get("out_tokens", 0) or 0)
                f_cost = float(fix_stats.get("cost", 0.0) or 0.0)

                in_tokens += f_in
                out_tokens += f_out
                cost_usd += f_cost

                # Normalize & validate fixed code (skip if API timed out)
                if fix_timed_out:
                    fix_valid, fix_error, fix_val_s = False, fix_err_msg, 0.0
                else:
                    fixed_code, sub_fixes = validate_and_fix(fixed_code)
                    fix_valid, fix_error, fix_val_s = validator.validate_code(fixed_code, mode=mode)

                fix_records.append({
                    "attempt": fix_i,
                    "wall_time_s": fix_wall_s,
                    "llm_time_s": fix_llm_s,
                    "val_time_s": fix_val_s,
                    "tokens_in": f_in,
                    "tokens_out": f_out,
                    "cost_usd": f_cost,
                    "valid": fix_valid,
                    "error_before": current_error[:200],
                    "error_after": fix_error[:200],
                })

                if verbose:
                    fix_tag = "PASS" if fix_valid else "FAIL"
                    print(
                        f"    [AUTO-FIX #{fix_i}] wall={fix_wall_s:.2f}s | val={fix_tag} ({fix_val_s:.2f}s)",
                        flush=True,
                    )

                current_code = fixed_code
                current_error = fix_error
                if fix_valid:
                    auto_fix_succeeded = True
                    resolved_attempt = fix_i
                    break
                if fix_timed_out:
                    break
                    break

        final_valid = initial_valid or auto_fix_succeeded
        fallback_triggered = False

        if not final_valid:
            # Fallback to RAG
            fallback_triggered = True
            current_code = rag_fallback or "(\n// Safe Fallback Sound\nNdef(\\safe, { SinOsc.ar(440) * 0.05!2 }).play;\n)"
            final_valid, _, _ = validator.validate_code(current_code, mode=mode)
            resolved_attempt = -1

        round_wall_s = time.perf_counter() - r_t0
        if mode == "design":
            design_runs_completed += 1

        # Append code to session .scd
        with open(session_scd, "a", encoding="utf-8") as f:
            f.write(
                f"\n// ============================================================\n"
                f"// ROUND {r_idx:02d} | MODE: {mode.upper()} | FRAG #{frag_id}\n"
                f"// STATUS: {'PASS' if initial_valid else ('FIXED' if auto_fix_succeeded else 'FALLBACK')}\n"
                f"// PROMPT: {prompt[:100]}...\n"
                f"// ============================================================\n"
                f"{current_code}\n\n"
            )

        round_rec = {
            "round_index": r_idx,
            "mode": mode,
            "mode_occurrence": mode_occ,
            "fragment_id": frag_id,
            "fragment_category": frag_cat,
            "fragment_source": frag_src,
            "prompt": prompt,
            "lean_wall_time_s": lean_wall_s,
            "lean_llm_time_s": lean_llm_s,
            "initial_val_time_s": initial_val_s,
            "in_tokens": in_tokens,
            "out_tokens": out_tokens,
            "cost_usd": cost_usd,
            "code_chars": len(code),
            "initial_valid": initial_valid,
            "initial_error": initial_error,
            "design_cleanup_required": needs_design_cleanup,
            "design_cleanup_applied": design_cleanup_applied,
            "design_cleanup_time_s": design_cleanup_time_s,
            "auto_fix_triggered": auto_fix_triggered,
            "auto_fix_attempts_used": auto_fix_attempts,
            "auto_fix_succeeded": auto_fix_succeeded,
            "resolved_on_attempt": resolved_attempt,
            "fallback_triggered": fallback_triggered,
            "final_valid": final_valid,
            "total_round_wall_time_s": round_wall_s,
            "validator_fixes": validator_fixes,
            "fix_attempts": fix_records,
        }
        rounds_data.append(round_rec)

        generated_codes.append({
            "round_index": r_idx,
            "mode": mode,
            "prompt": prompt,
            "initial_code": code,
            "final_code": current_code,
            "initial_valid": initial_valid,
            "final_valid": final_valid,
            "initial_error": initial_error,
            "validator_fixes": validator_fixes,
        })

    model_wall_s = time.perf_counter() - t_model_start

    # Calculate model metrics
    n_rounds = len(rounds_data)
    initial_passes = sum(1 for r in rounds_data if r["initial_valid"])
    final_passes = sum(1 for r in rounds_data if r["final_valid"])
    total_in_tokens = sum(r["in_tokens"] for r in rounds_data)
    total_out_tokens = sum(r["out_tokens"] for r in rounds_data)
    total_cost_usd = sum(r["cost_usd"] for r in rounds_data)
    total_fix_calls = sum(r["auto_fix_attempts_used"] for r in rounds_data)
    mean_llm_time_s = sum(r["lean_llm_time_s"] for r in rounds_data) / max(1, n_rounds)
    mean_wall_time_s = sum(r["total_round_wall_time_s"] for r in rounds_data) / max(1, n_rounds)
    mean_chars = sum(r["code_chars"] for r in rounds_data) / max(1, n_rounds)

    mode_stats: dict[str, dict[str, Any]] = {}
    for m in ["append", "compose", "design", "generate"]:
        m_rounds = [r for r in rounds_data if r["mode"] == m]
        if m_rounds:
            m_init_ok = sum(1 for r in m_rounds if r["initial_valid"])
            m_fin_ok = sum(1 for r in m_rounds if r["final_valid"])
            m_llm_time = sum(r["lean_llm_time_s"] for r in m_rounds) / len(m_rounds)
            m_cost = sum(r["cost_usd"] for r in m_rounds)
            m_chars = sum(r["code_chars"] for r in m_rounds) / len(m_rounds)
            mode_stats[m] = {
                "rounds": len(m_rounds),
                "init_pass_count": m_init_ok,
                "init_pass_rate": (m_init_ok / len(m_rounds)) * 100.0,
                "final_pass_count": m_fin_ok,
                "final_pass_rate": (m_fin_ok / len(m_rounds)) * 100.0,
                "mean_llm_time_s": m_llm_time,
                "total_cost_usd": m_cost,
                "mean_chars": m_chars,
            }

    summary = {
        "model_id": model_id,
        "model_name": model_name,
        "model_slug": model_slug,
        "total_rounds": n_rounds,
        "initial_pass_count": initial_passes,
        "initial_pass_rate": (initial_passes / max(1, n_rounds)) * 100.0,
        "final_pass_count": final_passes,
        "final_pass_rate": (final_passes / max(1, n_rounds)) * 100.0,
        "total_fix_calls": total_fix_calls,
        "total_in_tokens": total_in_tokens,
        "total_out_tokens": total_out_tokens,
        "total_tokens": total_in_tokens + total_out_tokens,
        "total_cost_usd": total_cost_usd,
        "mean_llm_time_s": mean_llm_time_s,
        "mean_wall_time_s": mean_wall_time_s,
        "model_total_wall_s": model_wall_s,
        "mean_code_chars": mean_chars,
        "mode_stats": mode_stats,
        "rounds": rounds_data,
        "generated_codes": generated_codes,
        "session_scd_file": session_scd,
    }
    return summary


def format_comparative_markdown(all_summaries: list[dict[str, Any]], schedule: list[dict[str, Any]]) -> str:
    """Format the complete comparative benchmark report in GitHub-flavored Markdown."""
    lines: list[str] = []
    lines.append("# Multi-Provider X-Append Lean Benchmark Report")
    lines.append(f"**Execution Date**: {datetime.now(timezone.utc).strftime('%Y-%m-%d %H:%M:%S UTC')}")
    lines.append(f"**Rounds per Model**: {len(schedule)} rounds across 4 modes (append, compose, design, generate)")
    lines.append(f"**Corpus Source**: 200-fragment pt-BR corpus (Wikipedia, Poema, Conto/Crônica, Descrição)")
    lines.append(f"**Providers**: OpenRouter (`google/gemini-3.8-flash`, `anthropic/claude-haiku-5.5`, `deepseek/deepseek-v4.1-flash`, `openai/gpt-6-luna`)\n")

    lines.append("## 1. Executive Summary & Leaderboard\n")
    lines.append("| Provider / Model | 1st-Pass Pass Rate | Final Pass Rate | Auto-Fix Used | Mean LLM Time | Mean Round Wall | Total Cost (USD) | Total Tokens | Mean Chars |")
    lines.append("|:---|:---:|:---:|:---:|:---:|:---:|:---:|:---:|:---:|")

    for s in all_summaries:
        m_name = s["model_name"]
        init_rate = f"{s['initial_pass_rate']:.1f}% ({s['initial_pass_count']}/{s['total_rounds']})"
        final_rate = f"{s['final_pass_rate']:.1f}% ({s['final_pass_count']}/{s['total_rounds']})"
        fixes = s["total_fix_calls"]
        llm_t = f"{s['mean_llm_time_s']:.2f}s"
        wall_t = f"{s['mean_wall_time_s']:.2f}s"
        cost = f"${s['total_cost_usd']:.5f}"
        toks = f"{s['total_tokens']:,}"
        chars = f"{s['mean_code_chars']:.0f}"
        lines.append(f"| **{m_name}** | {init_rate} | {final_rate} | {fixes} | {llm_t} | {wall_t} | {cost} | {toks} | {chars} |")

    lines.append("\n---\n")

    lines.append("## 2. Technical Efficiency & Cost Breakdown\n")
    lines.append("| Model | Total Wall Time | In Tokens | Out Tokens | Cost / 10 Rounds | Chars / Sec (Gen) |")
    lines.append("|:---|:---:|:---:|:---:|:---:|:---:|")
    for s in all_summaries:
        tot_wall = f"{s['model_total_wall_s']:.1f}s"
        in_tok = f"{s['total_in_tokens']:,}"
        out_tok = f"{s['total_out_tokens']:,}"
        cost = f"${s['total_cost_usd']:.5f}"
        chars_sec = f"{(s['mean_code_chars'] / max(0.1, s['mean_llm_time_s'])):.1f}"
        lines.append(f"| **{s['model_name']}** | {tot_wall} | {in_tok} | {out_tok} | {cost} | {chars_sec} c/s |")

    lines.append("\n---\n")

    lines.append("## 3. By-Mode Specialization Breakdown & Use-Case Analysis\n")
    lines.append("Evaluation of each model's strengths, compilation accuracy, and latency across the 4 specific SuperCollider use cases:\n")

    mode_descriptions = {
        "append": "Incremental live mutation, layer addition, and parameter evolution on a running session without interrupting playback.",
        "compose": "Long-form timeline scores, multi-layer polyphony, algorithmic structure, and acoustic storytelling via Tdef/Pbindef.",
        "design": "Playable hardware MIDI controller-mapped synthesizers, multi-zone keyboard layouts, and interactive GUI controls.",
        "generate": "Autonomous, continuously evolving multi-layer generative soundscapes with frequency bracketing and textural depth.",
    }

    for m in ["append", "compose", "design", "generate"]:
        m_upper = m.upper()
        lines.append(f"### Use Case: `{m_upper}` Mode")
        lines.append(f"*{mode_descriptions[m]}*\n")
        lines.append("| Model | 1st-Pass Pass Rate | Final Pass Rate | Mean LLM Time | Mode Cost (USD) | Mean Chars |")
        lines.append("|:---|:---:|:---:|:---:|:---:|:---:|")

        for s in all_summaries:
            st = s.get("mode_stats", {}).get(m, {})
            if st:
                init_str = f"{st['init_pass_rate']:.1f}% ({st['init_pass_count']}/{st['rounds']})"
                fin_str = f"{st['final_pass_rate']:.1f}% ({st['final_pass_count']}/{st['rounds']})"
                lat_str = f"{st['mean_llm_time_s']:.2f}s"
                cost_str = f"${st['total_cost_usd']:.5f}"
                ch_str = f"{st['mean_chars']:.0f}"
                lines.append(f"| **{s['model_name']}** | {init_str} | {fin_str} | {lat_str} | {cost_str} | {ch_str} |")
        lines.append("")

    lines.append("\n---\n")

    lines.append("## 4. Round-by-Round Comparative Matrix\n")
    lines.append("| Rnd | Mode | Prompt Fragment | " + " | ".join(f"{s['model_name']}" for s in all_summaries) + " |")
    lines.append("|:---:|:---:|:---| " + " | ".join(":---:" for _ in all_summaries) + " |")

    for idx, item in enumerate(schedule):
        r_num = item["round_index"]
        m_tag = item["mode"].upper()
        frag_title = f"#{item['fragment_id']} ({item['fragment_source'][:30]})"
        row_statuses = []
        for s in all_summaries:
            r_rec = s["rounds"][idx]
            if r_rec["initial_valid"]:
                st = f"✅ {r_rec['lean_llm_time_s']:.1f}s"
            elif r_rec["final_valid"]:
                st = f"⚠️ Fix#{r_rec['resolved_on_attempt']} ({r_rec['total_round_wall_time_s']:.1f}s)"
            else:
                st = f"❌ Fallback"
            row_statuses.append(st)
        lines.append(f"| {r_num:02d} | `{m_tag}` | {frag_title} | " + " | ".join(row_statuses) + " |")

    lines.append("\n---\n")

    lines.append("## 5. Model Details & Full Generated Code\n")
    for s in all_summaries:
        m_name = s["model_name"]
        lines.append(f"### Model: {m_name} (`{s['model_id']}`)\n")
        lines.append(f"- **Initial Pass Rate**: {s['initial_pass_rate']:.1f}%")
        lines.append(f"- **Final Pass Rate**: {s['final_pass_rate']:.1f}%")
        lines.append(f"- **Total Time**: {s['model_total_wall_s']:.2f}s (mean LLM: {s['mean_llm_time_s']:.2f}s/round)")
        lines.append(f"- **Total Tokens**: {s['total_tokens']:,} (Cost: ${s['total_cost_usd']:.5f})")
        lines.append(f"- **Executable SuperCollider File**: `{s['session_scd_file']}`\n")

        lines.append("#### Round Code Dumps:\n")
        for code_item in s["generated_codes"]:
            r_idx = code_item["round_index"]
            mode = code_item["mode"]
            prompt_snip = code_item["prompt"][:80].replace("\n", " ")
            status = "PASS" if code_item["initial_valid"] else ("FIXED" if code_item["final_valid"] else "FALLBACK")
            fixes_applied = ", ".join(code_item["validator_fixes"]) if code_item["validator_fixes"] else "None"

            lines.append(f"<details>")
            lines.append(f"<summary><strong>Round {r_idx:02d} [{mode.upper()}] - Status: {status}</strong> — <em>{prompt_snip}...</em></summary>\n")
            lines.append(f"- **Prompt**: {code_item['prompt']}")
            lines.append(f"- **Initial Valid**: {code_item['initial_valid']}")
            lines.append(f"- **Final Valid**: {code_item['final_valid']}")
            lines.append(f"- **Validator Fixes**: {fixes_applied}")
            if code_item["initial_error"]:
                lines.append(f"- **Initial Error**: `{code_item['initial_error'][:300]}`")
            lines.append("\n```supercollider")
            lines.append(code_item["final_code"])
            lines.append("```\n")
            lines.append("</details>\n")

    return "\n".join(lines)


def run_multi_provider_benchmark(
    seed: int = 101,
    rounds_per_model: int = DEFAULT_ROUNDS_PER_MODEL,
    max_fix_attempts: int = DEFAULT_MAX_FIX_ATTEMPTS,
    corpus_path: str = DEFAULT_CORPUS,
    use_specialization: bool = True,
    outdir: Optional[str] = None,
    verbose: bool = True,
) -> dict[str, Any]:
    """Execute the multi-provider 10-round benchmark across all 4 models."""
    if not outdir:
        timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")
        outdir = os.path.join(TESTS_DIR, "multi_provider_benchmark_output", f"run_{timestamp}")
    os.makedirs(outdir, exist_ok=True)

    print(f"Loading corpus from: {corpus_path}...")
    corpus_data = load_ptbr_corpus(corpus_path)
    fragments = corpus_data["fragments"]

    if use_specialization:
        schedule = build_specialization_benchmark_schedule(fragments, total_rounds=rounds_per_model)
    else:
        schedule = build_10_round_benchmark_schedule(fragments, total_rounds=rounds_per_model, seed=seed)

    print(f"Constructed benchmark schedule of {len(schedule)} rounds:")
    for s in schedule:
        print(f"  Round {s['round_index']:02d}: {s['mode'].upper():<8} [id={s['fragment_id']:03d}, {s['fragment_category']:<16}] {s['fragment_source']}")

    validator = SclangParallelValidator()
    val_started = validator.start()
    if not val_started:
        print("⚠ WARNING: SclangParallelValidator failed to boot. Structural checks will be used as fallback.")

    all_summaries: list[dict[str, Any]] = []

    try:
        for m_info in BENCHMARK_MODELS:
            m_summary = run_benchmark_for_model(
                model_info=m_info,
                schedule=schedule,
                validator=validator,
                max_fix_attempts=max_fix_attempts,
                outdir=outdir,
                verbose=verbose,
            )
            all_summaries.append(m_summary)

        # Generate markdown report
        md_report = format_comparative_markdown(all_summaries, schedule)
        md_path = os.path.join(outdir, "benchmark_report.md")
        with open(md_path, "w", encoding="utf-8") as f:
            f.write(md_report)

        # Save JSON data
        json_path = os.path.join(outdir, "benchmark_report.json")
        with open(json_path, "w", encoding="utf-8") as f:
            json.dump({
                "timestamp": datetime.now(timezone.utc).isoformat(),
                "seed": seed,
                "rounds_per_model": rounds_per_model,
                "max_fix_attempts": max_fix_attempts,
                "use_specialization": use_specialization,
                "models": all_summaries,
                "schedule": schedule,
            }, f, ensure_ascii=False, indent=2)

        print("\n" + "=" * 78)
        print(md_report[:2500] + "\n\n... [Full code and rounds saved to benchmark_report.md] ...")
        print("=" * 78)
        print(f"\n[COMPLETE] Multi-Provider Benchmark finished successfully!")
        print(f"Reports saved to: {outdir}")

        return {
            "outdir": outdir,
            "md_report_path": md_path,
            "json_report_path": json_path,
            "models": all_summaries,
        }

    finally:
        validator.stop()


def main() -> int:
    parser = argparse.ArgumentParser(description="Multi-Provider X-Append Lean Benchmark")
    parser.add_argument("--seed", type=int, default=101, help="Seed for fragment sampling (default: 101)")
    parser.add_argument("--rounds", type=int, default=8, help="Rounds per model (default: 8 for 2 per mode)")
    parser.add_argument("--max-fix", type=int, default=2, help="Max auto-fix attempts (default: 2)")
    parser.add_argument("--specialization", action="store_true", default=True, help="Use curated 4-mode specialization schedule")
    parser.add_argument("--outdir", default=None, help="Output directory")
    args = parser.parse_args()

    run_multi_provider_benchmark(
        seed=args.seed,
        rounds_per_model=args.rounds,
        max_fix_attempts=args.max_fix,
        use_specialization=args.specialization,
        outdir=args.outdir,
        verbose=True,
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
